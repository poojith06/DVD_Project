"""Replay EXACTLY the 10,000 input rows of each dataset CSV in ngspice and record, per row, the terminal currents
(-i(vd), -i(vg), -i(vs), -i(vb)) and the BSIM4 instance currents (@m1[id], ibd, ibs, isub, igidl, igisl, igs, igd,
igb, igcs, igcd).

Same sequence as Datasets/netlists/<case>_ngspice.cir per row: alter vd/vs/vg/vb, alter m1 w, one altermod line per
parameter (vth0, toxe, ndep, u0, xj), option temp, op. Input values are copied verbatim (as text) from the CSV.
OMP_WAIT_POLICY=passive: ngspice's OpenMP threads otherwise busy-wait (~90 ms per op instead of ~5 ms).
Values are written with `print ... >> file` and `set numdgt=12` (13 significant digits; the dataset's echo gives 6).

Usage: python make_replay.py [case ...] [--rows N]     -> <case>_replay.cir, <case>_replay.out, <case>_components.csv
"""
import sys, csv, subprocess, time
from pathlib import Path
import numpy as np, pandas as pd

HERE = Path(__file__).resolve().parent; REPO = HERE.parents[1]
CASES = {"nmos_on": "nmos", "nmos_off": "nmos", "pmos_on": "pmos", "pmos_off": "pmos"}
TERM = {"t_id": "-i(vd)", "t_ig": "-i(vg)", "t_is": "-i(vs)", "t_ib": "-i(vb)"}
COMP = ["id", "ibd", "ibs", "isub", "igidl", "igisl", "igs", "igd", "igb", "igcs", "igcd"]
NAMES = ["row"] + list(TERM) + [f"c_{c}" for c in COMP]
WSL_DIR = "/mnt/c/IIITH Academic/SEM 5/Digital VLSI Design/repo/Model_comparison/component_data"


def write_netlist(case, nrows=None):
    pol = CASES[case]
    with open(REPO / "Datasets" / "data" / f"{case}.csv", newline="") as f:
        rows = list(csv.DictReader(f))
    rows = rows[:nrows] if nrows else rows
    out = f"{case}_replay.out"
    L = [f"* {case} replay of Datasets/data/{case}.csv ({len(rows)} rows), generated by make_replay.py",
         ".options gmin=1e-18 abstol=1e-18 reltol=1e-6 vntol=1e-9",
         ".include ../../Datasets/netlists/22nm_HP.pm", "",
         "Vd d 0 dc 0", "Vg g 0 dc 0", "Vs s 0 dc 0", "Vb b 0 dc 0",
         f"M1 d g s b {pol} L=22n W=44n", "", ".control", "set numdgt=12", f"shell rm -f {out}"]
    for k, r in enumerate(rows):
        L += [f"alter vd dc = {r['vd']}", f"alter vs dc = {r['vs']}", f"alter vg dc = {r['vg']}", f"alter vb dc = {r['vb']}",
              f"alter m1 w = {r['w']}"]
        L += [f"altermod {pol} {p} = {r[p]}" for p in ("vth0", "toxe", "ndep", "u0", "xj")]
        L += [f"option temp = {r['temp']}", "op", f"let row = {k}"]
        L += [f"let {n} = {e}" for n, e in TERM.items()]
        L += [f"let c_{c} = @m1[{c}]" for c in COMP]
        L += [f"print {' '.join(NAMES)} >> {out}", "destroy all"]
    L += [".endc", ".end", ""]
    (HERE / f"{case}_replay.cir").write_text("\n".join(L), newline="\n")
    return len(rows)


def parse(case, nrows):
    vals = {n: [] for n in NAMES}
    for line in (HERE / f"{case}_replay.out").read_text().splitlines():
        if "=" in line:
            n, v = line.split("=", 1); vals[n.strip()].append(float(v))
    df = pd.DataFrame(vals); df["row"] = df["row"].astype(int)
    assert len(df) == nrows and (df["row"].to_numpy() == np.arange(nrows)).all(), f"{case}: missing rows"
    df.to_csv(HERE / f"{case}_components.csv", index=False, float_format="%.13g")
    return df


if __name__ == "__main__":
    args = sys.argv[1:]; nrows = None
    if "--rows" in args:
        i = args.index("--rows"); nrows = int(args[i + 1]); del args[i:i + 2]
    cases = args or list(CASES)
    procs = {}
    for case in cases:
        n = write_netlist(case, nrows)
        cmd = ["wsl", "-d", "Ubuntu", "--", "bash", "-c", f"cd '{WSL_DIR}' && OMP_WAIT_POLICY=passive ngspice -b {case}_replay.cir > {case}_replay.log 2>&1"]
        procs[case] = (subprocess.Popen(cmd), n, time.time())
    for case, (p, n, t0) in procs.items():
        p.wait(); df = parse(case, n)
        print(f"{case}: {n} rows in {time.time()-t0:.0f}s", flush=True)
