import numpy as np
import pandas as pd

SEED = 12
N_CORNERS = 200
VDD_NOM = 1.0  # V, assigned

# Nominal process values from 22nm_HP.pm
NMOS = dict(vth0=0.50308, toxe=1.05e-9, ndep=5.5e18, u0=0.04, xj=7.2e-9)
PMOS = dict(vth0=-0.4606, toxe=1.1e-9, ndep=4.4e18, u0=0.0095, xj=7.2e-9)
PARAMS = ["vth0", "toxe", "ndep", "u0", "xj"]

rng = np.random.default_rng(SEED)
df = pd.DataFrame({"corner": np.arange(N_CORNERS)})
df["vdd"] = VDD_NOM * rng.uniform(0.9, 1.1, N_CORNERS)
df["temp"] = rng.uniform(-40.0, 125.0, N_CORNERS)
for p in PARAMS:
    df[f"n_{p}"] = NMOS[p] * rng.uniform(0.9, 1.1, N_CORNERS)
for p in PARAMS:
    df[f"p_{p}"] = PMOS[p] * rng.uniform(0.9, 1.1, N_CORNERS)

df.to_csv("corners.csv", index=False, float_format="%.10g")

# ngspice vectors: negative numbers must be in parentheses inside 'compose'
with open("corners.inc", "w") as f:
    f.write(f"* {N_CORNERS} PVT corners generated by gen_corners.py (seed {SEED})\n")
    f.write("* vectors: c_vdd c_temp c_n_<param> c_p_<param>, index k = 0..%d\n" % (N_CORNERS - 1))
    f.write(".control\n")
    for col in df.columns[1:]:
        vals = " ".join(f"({v:.10g})" for v in df[col])
        f.write(f"compose c_{col} values {vals}\n")
    f.write(".endc\n")

print(f"Generated {N_CORNERS} corners with seed {SEED}")
print(df.drop(columns="corner").describe().loc[["min", "max"]].T.to_string())
print("Saved corners.csv and corners.inc")
