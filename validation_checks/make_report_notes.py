def md(df, fmts=None, index=False):
    fmts = fmts or {}
    cols = list(df.columns)
    esc = lambda s: str(s).replace("|", "\\|")
    rows = ["| " + " | ".join(esc(c) for c in cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if c in fmts and pd.notna(v):
                cells.append(esc(fmts[c](v)))
            elif isinstance(v, (float, np.floating)):
                cells.append("" if pd.isna(v) else f"{v:.4g}")
            else:
                cells.append(esc(v))
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join(rows)


