"""Make the training labels of components_mlp: the BSIM4 current components of every dataset row.

Replays EXACTLY the 10,000 input rows of Datasets/data/<case>.csv in ngspice (same steps as the dataset netlist per
row: alter vd/vs/vg/vb, alter m1 w, one altermod line per parameter, option temp, op) and records the terminal
currents (-i(vd), -i(vg), -i(vs), -i(vb)) and the BSIM4 instance currents @m1[id, ibd, ibs, isub, igidl, igisl, igs,
igd, igb, igcs, igcd]. The input values are copied verbatim (as text) from the CSV. Values are printed with
13 significant digits.

Needs ngspice in WSL (Ubuntu). Takes about 3 minutes per case.
Usage: python components_mlp/make_components.py [case ...]
Output: component_data/<case>_replay.cir (the generated netlist), <case>_components.csv (row, t_id..t_ib, c_id..c_igcd)
"""
import csv
import subprocess
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent / "component_data"
REPO = Path(__file__).resolve().parents[2]
CASES = {"nmos_on": "nmos", "nmos_off": "nmos", "pmos_on": "pmos", "pmos_off": "pmos"}
TERM = {"t_id": "-i(vd)", "t_ig": "-i(vg)", "t_is": "-i(vs)", "t_ib": "-i(vb)"}
COMP = ["id", "ibd", "ibs", "isub", "igidl", "igisl", "igs", "igd", "igb", "igcs", "igcd"]
NAMES = ["row"] + list(TERM) + [f"c_{c}" for c in COMP]


def wsl_path(p: Path) -> str:
    p = p.resolve()
    return f"/mnt/{p.drive[0].lower()}{p.as_posix()[2:]}"


def write_netlist(case):
    pol = CASES[case]
    with open(REPO / "Datasets" / "data" / f"{case}.csv", newline="") as f:
        rows = list(csv.DictReader(f))
    out = f"{case}_replay.out"
    L = [f"* {case}: replay of Datasets/data/{case}.csv ({len(rows)} rows), generated by make_components.py",
         ".options gmin=1e-18 abstol=1e-18 reltol=1e-6 vntol=1e-9",
         ".include ../../../Datasets/netlists/22nm_HP.pm", "",
         "Vd d 0 dc 0", "Vg g 0 dc 0", "Vs s 0 dc 0", "Vb b 0 dc 0",
         f"M1 d g s b {pol} L=22n W=44n", "", ".control", "set numdgt=12", f"shell rm -f {out}"]
    for k, r in enumerate(rows):
        L += [f"alter vd dc = {r['vd']}", f"alter vs dc = {r['vs']}", f"alter vg dc = {r['vg']}",
              f"alter vb dc = {r['vb']}", f"alter m1 w = {r['w']}"]
        L += [f"altermod {pol} {p} = {r[p]}" for p in ("vth0", "toxe", "ndep", "u0", "xj")]
        L += [f"option temp = {r['temp']}", "op", f"let row = {k}"]
        L += [f"let {n} = {e}" for n, e in TERM.items()]
        L += [f"let c_{c} = @m1[{c}]" for c in COMP]
        L += [f"print {' '.join(NAMES)} >> {out}", "destroy all"]
    L += [".endc", ".end", ""]
    (HERE / f"{case}_replay.cir").write_text("\n".join(L), newline="\n")
    return len(rows)


def parse(case, nrows):
    vals = {n: [] for n in NAMES}
    for line in (HERE / f"{case}_replay.out").read_text().splitlines():
        if "=" in line:
            n, v = line.split("=", 1)
            vals[n.strip()].append(float(v))
    df = pd.DataFrame(vals)
    df["row"] = df["row"].astype(int)
    if len(df) != nrows or not (df["row"].to_numpy() == np.arange(nrows)).all():
        raise RuntimeError(f"{case}: ngspice output is missing rows - see {case}_replay.log")
    df.to_csv(HERE / f"{case}_components.csv", index=False, float_format="%.13g")
    (HERE / f"{case}_replay.out").unlink()
    return df


if __name__ == "__main__":
    HERE.mkdir(exist_ok=True)
    for case in sys.argv[1:] or list(CASES):
        t0 = time.time()
        n = write_netlist(case)
        subprocess.run(["wsl", "-d", "Ubuntu", "--", "bash", "-c",
                        f"cd '{wsl_path(HERE)}' && OMP_WAIT_POLICY=passive ngspice -b {case}_replay.cir "
                        f"> {case}_replay.log 2>&1"], check=True)
        parse(case, n)
        print(f"{case}: {n} rows in {time.time() - t0:.0f}s", flush=True)
